#!/usr/bin/env python3
"""Regenerate the Go business migrations with Django's PostgreSQL SQL collector."""

import argparse
from contextlib import contextmanager
from copy import copy
from datetime import date, datetime, time, timezone
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import tempfile
from unittest.mock import patch
from uuid import UUID

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / 'BE_GO/migrations/business'
HEADER = '-- Generated by tools/go-migration/business_schema.py.\n'
RECORDER = '000100_django_migrations.up.sql'

# Callable field defaults become one-shot SQL defaults. Fixed defaults are left
# as Django emitted them. The temporary defaults are dropped by Django's DDL.
VOLATILE = {
    datetime: (datetime(8999, 6, 7, 8, 9, 10, tzinfo=timezone.utc), 'statement_timestamp()'),
    date: (date(8999, 6, 7), 'CURRENT_DATE'),
    time: (time(8, 9, 10, 678987), 'LOCALTIME'),
    UUID: (UUID('89990607-0809-4000-8000-000000000000'), 'gen_random_uuid()'),
}
VOLATILE_CALLABLES = {
    ('application.models.courses_models', 'random_color'): (
        '#899907', "('#' || lpad(to_hex(floor(random() * 16777216)::integer), 6, '0'))",
    ),
}


@contextmanager
def postgres(binaries):
    """Use an empty cluster created by this invocation. Never use deployment settings."""
    with tempfile.TemporaryDirectory(prefix='g') as directory:
        work = Path(directory).resolve()
        data = work / 'db'
        socket = work

        def run(tool, *args):
            executable = binaries / tool if binaries else tool
            subprocess.run([executable, *args], check=True, stdout=subprocess.DEVNULL)

        run('initdb', '-D', data, '-U', 'schema', '-A', 'trust', '--no-locale', '-E', 'UTF8', '--no-sync')
        log = work / 'postgres.log'
        try:
            run('pg_ctl', '-D', data, '-l', log, '-o',
                f"-k {shlex.quote(str(socket))} -h '' -F -p 55432 -c timezone=UTC", '-w', 'start')
        except subprocess.CalledProcessError:
            print(log.read_text(), file=sys.stderr)
            raise
        try:
            yield work, socket
        finally:
            run('pg_ctl', '-D', data, '-m', 'immediate', '-w', 'stop')


@contextmanager
def django_settings(work, socket):
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    values = {}
    for line in (ROOT / 'selfhost/.env.example').read_text().splitlines():
        key, sep, value = line.partition('=')
        if sep and not key.startswith('#'):
            values[key.strip()] = value.strip().strip('"').strip("'")
    key = Ed25519PrivateKey.generate()
    values.update(
        DJANGO_SETTINGS_MODULE='core.settings', DEBUG='False', STORE_ON_DISK='True',
        DBTYPE='POSTGRES', DBNAME='postgres', DBUSER='schema', DBPASSWORD='',
        DBHOST=str(socket), DBPORT='55432', USE_PGBOUNCER='False',
        JWT_SECRET_KEY_B64='', JWT_PUBLIC_KEY_B64='',
        JWT_SECRET_KEY=key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                         serialization.NoEncryption()).decode(),
        JWT_PUBLIC_KEY=key.public_key().public_bytes(serialization.Encoding.PEM,
                                                     serialization.PublicFormat.SubjectPublicKeyInfo).decode(),
        STORAGE_DIR=str(work / 'storage'), DATA_RESTORE_LOCK_PATH=str(work / 'lifecycle.lock'),
        GO_TASK_QUEUE_TASKS='', EMAIL_HOST_USER='noreply@example.test',
    )
    sys.path.insert(0, str(ROOT / 'BE'))
    with patch.dict(os.environ, values, clear=True), patch('environ.Env.read_env'):
        import django
        django.setup()
        yield


def collect_migration(connection, migration, state):
    from django.db.migrations import RunPython
    from django.contrib.contenttypes.management import RenameContentType

    # sqlmigrate collects without running DDL. Historical migrations can inspect
    # a constraint installed earlier in the same migration. Apply each statement
    # in the private cluster as Django collects it so that introspection is real.
    collector = connection.schema_editor(collect_sql=True)
    operations = []
    with connection.schema_editor(atomic=migration.atomic) as editor:
        execute = editor.execute
        effective_default = editor.effective_default
        defaults = {editor.quote_value(marker): expression
                    for marker, expression in (*VOLATILE.values(), *VOLATILE_CALLABLES.values())}

        def collect_and_execute(statement, params=()):
            collector.execute(statement, params)
            execute(statement, params)

        def stable_default(field):
            default = field.default
            key = (getattr(default, '__module__', None), getattr(default, '__name__', None))
            if key in VOLATILE_CALLABLES:
                return VOLATILE_CALLABLES[key][0]
            value = effective_default(field)
            if type(value) in VOLATILE and (
                callable(field.default) or getattr(field, 'auto_now', False) or getattr(field, 'auto_now_add', False)
            ):
                return VOLATILE[type(value)][0]
            return value

        editor.execute = collect_and_execute
        editor.effective_default = stable_default
        for operation in migration.operations:
            if isinstance(operation, RunPython):
                original = operation.database_forwards
                marker = operation.code.__name__
                if isinstance(operation, RenameContentType):
                    marker = f'rename_content_type_{operation.old_model}_to_{operation.new_model}'
                adapted = copy(operation)

                def data_operation(app, schema_editor, before, after, original=original, marker=marker):
                    if marker == 'update_proxy_model_permissions' and any(
                        model._meta.proxy for model in before.apps.get_models()
                    ):
                        raise ValueError('The port of auth.0011 needs the historical proxy models')
                    if marker != 'noop':
                        collector.collected_sql.append(f'-- django-data: {app}.{marker}')
                    with patch.object(schema_editor, 'execute', execute):
                        original(app, schema_editor, before, after)

                adapted.database_forwards = data_operation
                operation = adapted
            operations.append(operation)

        edited_migration = copy(migration)
        edited_migration.operations = operations
        state = edited_migration.apply(state, editor)

    sql = '\n'.join(
        statement.rstrip() if statement.lstrip().startswith(('CREATE INDEX ', 'CREATE UNIQUE INDEX ')) else statement
        for statement in collector.collected_sql
    )
    for quoted, expression in defaults.items():
        sql = sql.replace(quoted, expression)
    return state, sql


def post_migrate(connection, state):
    from django.apps import apps
    from django.contrib.auth.management import _get_all_permissions

    models, permissions = [], []
    quote = connection.schema_editor().quote_value
    for config in apps.get_app_configs():
        if not config.models_module or config.label not in state.apps.app_configs:
            continue
        # ProjectState can reload a set of models in hash order. Only natural
        # keys are shared with Django, and existing rows keep their numeric IDs.
        for model in sorted(state.apps.get_app_config(config.label).get_models(),
                            key=lambda model: model._meta.model_name):
            name = model._meta.model_name
            models.append((config.label, name))
            permissions.extend((config.label, name, code, str(label))
                               for code, label in _get_all_permissions(model._meta))

    def values(rows):
        return ',\n'.join(f"    ({index}, {', '.join(map(quote, row))})" for index, row in enumerate(rows, 1))

    return f"""INSERT INTO django_content_type (app_label, model)
SELECT available.app_label, available.model
FROM (VALUES
{values(models)}
) AS available(position, app_label, model)
WHERE NOT EXISTS (
    SELECT 1 FROM django_content_type existing
    WHERE (existing.app_label, existing.model) = (available.app_label, available.model)
)
ORDER BY available.position;

INSERT INTO auth_permission (content_type_id, codename, name)
SELECT content_type.id, available.codename, available.name
FROM (VALUES
{values(permissions)}
) AS available(position, app_label, model, codename, name)
JOIN django_content_type content_type USING (app_label, model)
WHERE NOT EXISTS (
    SELECT 1 FROM auth_permission existing
    WHERE (existing.content_type_id, existing.codename) = (content_type.id, available.codename)
)
ORDER BY available.position;
"""


def generate():
    from django.contrib.contenttypes.management import inject_rename_contenttypes_operations
    from django.db import connection
    from django.db.migrations.executor import MigrationExecutor
    from django.db.migrations.recorder import MigrationRecorder

    executor = MigrationExecutor(connection)
    graph = executor.loader.graph
    conflicts = executor.loader.detect_conflicts()
    if conflicts:
        raise ValueError(f'Django migration conflicts: {conflicts}')
    plan = executor.migration_plan(graph.leaf_nodes(), clean_start=True)
    inject_rename_contenttypes_operations(plan)
    state = executor._create_project_state()
    manifest = DEST / 'plan.json'
    prior = json.loads(manifest.read_text()) if manifest.exists() else []
    paths = {(entry['app'], entry['name']): entry['sql'] for entry in prior}
    version = max([100, *(int(path.split('_', 1)[0]) for path in paths.values())])
    entries = []
    files = {}

    recorder = MigrationRecorder(connection)
    with connection.schema_editor(collect_sql=True) as editor:
        editor.create_model(recorder.Migration)
    files[RECORDER] = HEADER + '\n'.join(editor.collected_sql).replace('CREATE TABLE ', 'CREATE TABLE IF NOT EXISTS ', 1) + '\n'
    recorder.ensure_schema()
    for migration, backward in plan:
        if backward or not migration.atomic:
            raise ValueError(f'Go needs an explicit port for non-atomic or reverse migration {migration}')
        app, name = migration.app_label, migration.name
        path = paths.get((app, name))
        if path is None:
            version += 1
            path = f'{version:06}_{app}_{name}.up.sql'
        print(f'Collecting {migration}', flush=True)
        state, sql = collect_migration(connection, migration, state)
        files[path] = HEADER + f'-- Django migration: {migration}\n' + (sql + '\n' if sql else '')
        entry = {'app': app, 'name': name, 'sql': path}
        if migration.replaces:
            entry['replaces'] = migration.replaces
        entries.append(entry)
        executor.record_migration(migration)

    files['plan.json'] = json.dumps(entries, indent=2) + '\n'
    files['post_migrate.sql'] = HEADER + post_migrate(connection, state)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=['write', 'check'])
    parser.add_argument('--pg-bin', type=Path, help='directory containing initdb and pg_ctl')
    arguments = parser.parse_args()
    with postgres(arguments.pg_bin) as (work, socket), django_settings(work, socket):
        files = generate()

    manual = {key for source in files.values() for key in re.findall(r'^-- django-data: (\S+)$', source, re.M)}
    sql_ports = {path.with_suffix('').name for path in (DEST / 'data').glob('*.sql')}
    go_ports = {'application.migrate_subscription_signature_compatibility'}
    if manual != sql_ports | go_ports:
        raise SystemExit(f'Manual ports differ. Missing: {sorted(manual - sql_ports - go_ports)}. '
                         f'Unused: {sorted((sql_ports | go_ports) - manual)}.')
    stale = sorted(path.name for path in DEST.glob('*.up.sql') if path.name not in files)
    if stale:
        raise SystemExit(f'Review retired Django migrations before removing: {stale}')
    if arguments.mode == 'write':
        for name, source in files.items():
            (DEST / name).write_text(source)
        return 0
    changed = [name for name, source in files.items()
               if not (DEST / name).exists() or (DEST / name).read_text() != source]
    if changed:
        print('Regenerate business schema: ' + ', '.join(changed), file=sys.stderr)
    return int(bool(changed))


if __name__ == '__main__':
    # Django's historical model reloads traverse sets. Regenerate their
    # statement order consistently regardless of the caller's hash seed.
    if sys.flags.hash_randomization:
        os.execve(sys.executable, [sys.executable, '-B', str(Path(__file__).resolve()), *sys.argv[1:]],
                  {**os.environ, 'PYTHONHASHSEED': '0'})
    raise SystemExit(main())
