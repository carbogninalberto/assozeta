export function memberAdditionalReferences(source) {
    if (typeof source !== 'function') throw new TypeError('Member additional references require a source reader');
    const references = new Map();
    for (const [index, contract] of memberAdditionalSourceContracts.entries()) {
        const reference = source(...contract);
        if (!reference || reference.path !== contract[0] ||
            reference.canonical_source_sha256 !== memberAdditionalReviewedSources[contract[0]])
            throw new Error('Member additional source evidence changed; review required: ' + contract[0]);
        references.set(sourceKeys[index], reference);
    }
    return sections.map(({contracts, ...descriptor}) => ({...descriptor,
        evidence: contracts.map(key => references.get(key))}));
}
