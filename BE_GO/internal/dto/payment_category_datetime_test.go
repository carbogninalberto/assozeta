func TestPaymentCategoryDateTimeOverflowClassification(t *testing.T) {
	for _, input := range []string{"0001-01-01T00:00:00+01:00", "9999-12-31T23:59:59-01:00", "0001-1-1T0:0:0+01"} {
		if _, err := parsePaymentCategoryDjangoDateTime(input); !errors.Is(err, errPaymentCategoryDateTimeOverflow) {
			t.Fatalf("UTC overflow %q: %v", input, err)
		}
	}
	for _, input := range []string{"0000-01-01", "9999-W52-7", "2021-02-29", "2021-01-01T24:00Z"} {
		if _, err := parsePaymentCategoryDjangoDateTime(input); err == nil || errors.Is(err, errPaymentCategoryDateTimeOverflow) {
			t.Fatalf("calendar/time format %q must not be UTC overflow: %v", input, err)
		}
	}
}

func TestPaymentCategoryDateTimeSurrogateSeparator(t *testing.T) {
	for _, tc := range []struct{ input, want string }{
		{"2021-01-02\xed\xa0\x8003:04", "2021-01-02T03:04:00.000000Z"},
		{"2021W01\xed\xb0\x8003:04", "2021-01-04T03:04:00.000000Z"},
	} {
		got, err := parsePaymentCategoryDjangoDateTime(tc.input)
		if err != nil || got.Format("2006-01-02T15:04:05.000000Z07:00") != tc.want {
			t.Fatalf("surrogate separator: %v %v", got, err)
		}
	}
	if _, err := parsePaymentCategoryDjangoDateTime("2021-\xed\xa0\x801-02T03:04"); err == nil {
		t.Fatal("surrogate inside date digits must be rejected")
	}
}

func FuzzPaymentCategoryDateTime(f *testing.F) {
	for _, seed := range []string{"", "2021-01-02T03:04:05Z", "2021W01112345678", "2021-W01-1x03:04", "2021-1-2T3:4:5", "2021-01-02T03:04:+01.5", "0001-01-01T00:00+01", "2021-01-02\xed\xa0\x8003:04"} {
		f.Add(seed)
	}
	f.Fuzz(func(t *testing.T, value string) {
		parsed, err := parsePaymentCategoryDjangoDateTime(value)
		if err == nil {
			if parsed.Year() < 1 || parsed.Year() > 9999 || parsed.Nanosecond()%1000 != 0 {
				t.Fatalf("accepted value outside Python datetime range/precision: %v", parsed)
			}
			_, offset := parsed.Zone()
			if offset != 0 {
				t.Fatalf("response time must be UTC: %v", parsed)
			}
		}
	})
}
