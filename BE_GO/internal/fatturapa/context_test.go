func mustDecimal(t *testing.T, text string) decimal {
	t.Helper()
	value, ok := parseDecimal(text)
	if !ok {
		t.Fatalf("Decimal(%q) raised", text)
	}
	return value
}

func TestContextArithmetic(t *testing.T) {
	for _, tc := range contextArithmetic {
		a, b := mustDecimal(t, tc.a), mustDecimal(t, tc.b)
		for _, op := range []struct {
			name string
			want string
			do   func() (decimal, error)
		}{
			{"+", tc.sum, func() (decimal, error) { return a.add(b) }},
			{"*", tc.product, func() (decimal, error) { return a.mul(b) }},
		} {
			got, err := op.do()
			switch {
			case op.want == "":
				if !errors.Is(err, ErrInvalid) {
					t.Errorf("%s %s %s = %v, %v; want ErrInvalid (Overflow)", tc.a, op.name, tc.b, got, err)
				}
			case err != nil || got.String() != op.want:
				t.Errorf("%s %s %s = %v, %v; want %q", tc.a, op.name, tc.b, got, err, op.want)
			}
		}
	}
}

func TestContextDivisionBy100(t *testing.T) {
	for _, tc := range contextDivision {
		got, err := mustDecimal(t, tc.a).div100()
		if err != nil || got.String() != tc.quotient {
			t.Errorf("%s / 100 = %v, %v; want %q", tc.a, got, err, tc.quotient)
		}
	}
}

