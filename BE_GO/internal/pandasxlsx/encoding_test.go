// The parts below are the bytes ElementTree.fromstring (expat, the parser
// openpyxl uses without lxml) reads, recorded with the reference CPython
// 3.13.16 and its expat 2.9.0: the text it answers, or the exception it
// raises (every class here is ErrInvalid for the package).
type encodingCase struct {
	name     string
	part     string
	text     string // the text of <a>, or "" when expat refuses the part
	declared string // a declaration written for the test, when the recorded one has no attribute
}

func (c encodingCase) bytes(t *testing.T) []byte {
	t.Helper()
	raw, err := hex.DecodeString(c.part)
	if err != nil {
		t.Fatalf("%s: %v", c.name, err)
	}
	return raw
}

// TestXMLEncodings is the part -> text step: expat's built-in encodings, the
// single-byte maps pyexpat's unknown-encoding handler builds from
// bytes.decode(name, 'replace'), the multi-byte codecs it refuses, and the
// declarations expat refuses as inconsistent with the bytes.
func TestXMLEncodings(t *testing.T) {
	for _, tc := range xmlEncodingCases {
		t.Run(tc.name, func(t *testing.T) {
			var value struct {
				XMLName xml.Name `xml:"a"`
				Text    string   `xml:",chardata"`
			}
			err := decode(tc.bytes(t), &value)
			switch {
			case tc.text == "":
				if err == nil {
					t.Fatalf("read %q, expat refuses the part", value.Text)
				}
			case err != nil:
				t.Fatalf("%v, expat reads %q", err, tc.text)
			case value.Text != tc.text:
				t.Fatalf("read %q, expat reads %q", value.Text, tc.text)
			}
		})
	}
}

