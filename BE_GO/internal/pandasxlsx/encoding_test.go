// TestXMLDeclarationSyntax is the declaration grammar: expat reads
// single-quoted values and standalone, and refuses a declaration without a
// version or with an attribute it does not know.
func TestXMLDeclarationSyntax(t *testing.T) {
	parts := map[string]struct {
		text string
		want string // "" when expat refuses the declaration
	}{
		"single-quote":      {"<?xml version='1.0' encoding='ISO-8859-1'?><a>Citt\xe0</a>", "Citt\u00e0"},
		"standalone":        {"<?xml version=\"1.0\" encoding=\"ISO-8859-1\" standalone=\"yes\"?><a>Citt\xe0</a>", "Citt\u00e0"},
		"version-1.1":       {"<?xml version=\"1.1\"?><a>x</a>", "x"},
		"comment-decl-text": {`<!-- <?xml version="1.0"?> --><a>x</a>`, "x"},
		"no-version":        {`<?xml encoding="ISO-8859-1"?><a>x</a>`, ""},
		"unknown-attr":      {`<?xml version="1.0" foo="x"?><a>x</a>`, ""},
		"bad-version":       {`<?xml version="2.0"?><a>x</a>`, ""},
		"bad-standalone":    {`<?xml version="1.0" standalone="maybe"?><a>x</a>`, ""},
		"after-space":       {` <?xml version="1.0"?><a>x</a>`, ""},
		"after-comment":     {`<!--x--><?xml version="1.0"?><a>x</a>`, ""},
	}
	for name, tc := range parts {
		t.Run(name, func(t *testing.T) {
			var value struct {
				XMLName xml.Name `xml:"a"`
				Text    string   `xml:",chardata"`
			}
			err := decode([]byte(tc.text), &value)
			switch {
			case tc.want == "":
				if err == nil {
					t.Fatalf("read %q, expat refuses the declaration", value.Text)
				}
			case err != nil:
				t.Fatalf("%v, expat reads %q", err, tc.want)
			case value.Text != tc.want:
				t.Fatalf("read %q, expat reads %q", value.Text, tc.want)
			}
		})
	}
}

