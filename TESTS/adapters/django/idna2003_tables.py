"""Generate, or check, the nameprep tables that the Go server embeds for Python's 'idna' codec.

str.encode('idna') maps each non-ASCII label through nameprep (RFC 3491 on the stringprep tables of the
pinned interpreter) and then Punycode. Go reproduces it in BE_GO/internal/idna2003 from the ranges written here:

  python TESTS/adapters/django/idna2003_tables.py --write
  python TESTS/adapters/django/idna2003_tables.py --check
"""
import argparse
import stringprep
import subprocess
import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[3] / 'BE_GO/internal/idna2003/tables.go'
PROHIBITED = (stringprep.in_table_c12, stringprep.in_table_c22, stringprep.in_table_c3, stringprep.in_table_c4,
              stringprep.in_table_c5, stringprep.in_table_c6, stringprep.in_table_c7, stringprep.in_table_c8,
              stringprep.in_table_c9)


def go_escape(text):
    return ''.join(c if c.isascii() and c.isalnum() else f'\\U{ord(c):08x}' for c in text)


def ranges(predicate):
    found, start = [], None
    for code in range(0x110000):
        if predicate(chr(code)):
            if start is None:
                start = code
        elif start is not None:
            found.append((start, code - 1))
            start = None
    if start is not None:
        found.append((start, 0x10FFFF))
    return found


def go_ranges(name, comment, table):
    lines = [f'// {comment}', f'var {name} = [][2]rune{{']
    lines += [f'\t{{0x{low:X}, 0x{high:X}}},' for low, high in table]
    return lines + ['}', '']


def render():
    mapping = {}
    for code in range(0x110000):
        character = chr(code)
        if 0xD800 <= code <= 0xDFFF or stringprep.in_table_b1(character):
            continue
        mapped = stringprep.map_table_b2(character)
        if mapped != character:
            mapping[code] = mapped
    lines = ['// Code generated by TESTS/adapters/django/idna2003_tables.py; DO NOT EDIT.', '', 'package idna2003', '']
    lines += go_ranges('mappedToNothing', 'RFC 3454 table B.1.', ranges(stringprep.in_table_b1))
    lines += ['// caseFolding is RFC 3454 table B.2 as Python applies it (map_table_b2).', 'var caseFolding = map[rune]string{']
    for code, mapped in sorted(mapping.items()):
        lines.append(f'\t0x{code:X}: "{go_escape(mapped)}",')
    lines += ['}', '']
    lines += go_ranges('prohibited', 'Tables C.1.2, C.2.2 and C.3 to C.9.',
                       ranges(lambda c: any(table(c) for table in PROHIBITED)))
    lines += go_ranges('randALTable', 'Table D.1 (bidirectional RandALCat).', ranges(stringprep.in_table_d1))
    lines += go_ranges('lCat', 'Table D.2 (bidirectional LCat).', ranges(stringprep.in_table_d2))
    lines.append(f'// unicodeVersion is the version of the interpreter\'s unicodedata: {unicodedata.unidata_version}.')
    lines.append(f'const unicodeVersion = "{unicodedata.unidata_version}"')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    text = render()
    text = subprocess.run(['gofmt'], input=text, capture_output=True, text=True, check=True).stdout
    if arguments.write:
        OUTPUT.write_text(text)
    elif arguments.check:
        if OUTPUT.read_text() != text:
            sys.exit('tables.go is stale: run idna2003_tables.py --write')
    else:
        parser.error('--write or --check')
