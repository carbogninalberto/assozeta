"""Generate, or check, the CSRF failure page data that the Go server embeds.

CsrfViewMiddleware answers a rejected request with django.views.csrf.csrf_failure:
403 and a page built from eight gettext messages (translated per active language),
in one of three forms (no Referer header, no CSRF cookie, any other reason). With
DEBUG off the reason text itself is not shown. Go serves the page from
BE_GO/internal/handler/csrf_failure_catalog.go:

  python TESTS/adapters/django/csrf_failure_pages.py --write
  python TESTS/adapters/django/csrf_failure_pages.py --check

Every language of the read-route language list is rendered by Django's own view
and compared with the page assembled the way Go does.
"""
import argparse
import html
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / 'BE_GO/internal/handler/csrf_failure_catalog.go'
LANGUAGES_SOURCE = ROOT / 'BE_GO/internal/handler/rest_route_locale.go'
NAMES = ('title', 'main', 'no_referer1', 'no_referer2', 'no_referer3', 'no_cookie1', 'no_cookie2', 'more')


def languages():
    block = re.search(r'var readRouteLanguages = \[\]string\{(.*?)\n\}', LANGUAGES_SOURCE.read_text(), re.S).group(1)
    return re.findall(r'"([a-z-]+)"', block)


def go_string(text):
    return '`' + text + '`' if '`' not in text else '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def build():
    sys.path.insert(0, str(Path(__file__).parent))
    from api_schema import setup_django
    stack = setup_django()
    stack.enter_context(__import__('contextlib').nullcontext())
    from django.template import Context, Engine
    from django.test import RequestFactory
    from django.utils import translation
    from django.utils.translation import gettext as _
    from django.views import csrf
    from django.middleware.csrf import REASON_NO_CSRF_COOKIE, REASON_NO_REFERER, REASON_BAD_ORIGIN

    template = csrf.builtin_template_path('csrf_403.html').read_text(encoding='utf-8')
    engine = Engine()
    sentinel = {name: f'@@{name}@@' for name in NAMES}
    skeletons = {}
    for variant, flags in (('other', (False, False)), ('referer', (True, False)), ('cookie', (False, True))):
        context = {**sentinel, 'reason': '', 'no_referer': flags[0], 'no_cookie': flags[1], 'DEBUG': False}
        skeletons[variant] = engine.from_string(template).render(Context(context))

    def assemble(variant, messages):
        page = skeletons[variant]
        for name in NAMES:
            page = page.replace(f'@@{name}@@', html.escape(messages[name], quote=True).replace('&#x27;', '&#x27;'))
        return page

    request = RequestFactory().post('/chat/test/')
    catalog = {}
    for language in languages():
        with translation.override(language):
            messages = {
                'title': _('Forbidden'), 'main': _('CSRF verification failed. Request aborted.'),
                'no_referer1': _('You are seeing this message because this HTTPS site requires a “Referer header” to be sent by your web browser, but none was sent. This header is required for security reasons, to ensure that your browser is not being hijacked by third parties.'),
                'no_referer2': _('If you have configured your browser to disable “Referer” headers, please re-enable them, at least for this site, or for HTTPS connections, or for “same-origin” requests.'),
                'no_referer3': _('If you are using the <meta name="referrer" content="no-referrer"> tag or including the “Referrer-Policy: no-referrer” header, please remove them. The CSRF protection requires the “Referer” header to do strict referer checking. If you’re concerned about privacy, use alternatives like <a rel="noreferrer" …> for links to third-party sites.'),
                'no_cookie1': _('You are seeing this message because this site requires a CSRF cookie when submitting forms. This cookie is required for security reasons, to ensure that your browser is not being hijacked by third parties.'),
                'no_cookie2': _('If you have configured your browser to disable cookies, please re-enable them, at least for this site, or for “same-origin” requests.'),
                'more': _('More information is available with DEBUG=True.'),
            }
            for variant, reason in (('other', REASON_BAD_ORIGIN % 'https://x.test'), ('referer', REASON_NO_REFERER),
                                    ('cookie', REASON_NO_CSRF_COOKIE)):
                real = csrf.csrf_failure(request, reason).content.decode()
                assert real == assemble(variant, messages), (language, variant)
        catalog[language] = messages
    return skeletons, catalog


def render(skeletons, catalog):
    lines = ['// Code generated by TESTS/adapters/django/csrf_failure_pages.py; DO NOT EDIT.', '',
             'package handler', '',
             '// csrfFailureSkeletons are django.views.csrf.csrf_failure pages (DEBUG off) with @@name@@ placeholders.',
             'var csrfFailureSkeletons = map[string]string{']
    for variant, page in skeletons.items():
        lines.append(f'\t"{variant}": {go_string(page)},')
    lines += ['}', '', '// csrfFailureCatalogs holds the gettext messages per language of the read-route language list.',
              'var csrfFailureCatalogs = map[string]map[string]string{']
    for language, messages in catalog.items():
        lines.append(f'\t"{language}": {{')
        for name in NAMES:
            lines.append(f'\t\t"{name}": {go_string(messages[name])},')
        lines.append('\t},')
    lines += ['}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    text = render(*build())
    text = subprocess.run(['gofmt'], input=text, capture_output=True, text=True, check=True).stdout
    if arguments.write:
        OUTPUT.write_text(text)
    elif arguments.check:
        if OUTPUT.read_text() != text:
            sys.exit('csrf_failure_catalog.go is stale: run csrf_failure_pages.py --write')
    else:
        parser.error('--write or --check')
