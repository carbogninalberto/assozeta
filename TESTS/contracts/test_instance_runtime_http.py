"""Phase 1 handoff: Django and Go expose the same runtime switch; no Django imports.

One authored sequence (fixtures/instance_runtime_http.json, generated by
fixtures/generate_instance_runtime_http.py) runs unchanged against native
Django and native Go (and Caddy /api/v1, /api/v2 with --versioned):
    python3 tools/go-migration/family.py run instance-runtime [--versioned]
Per response: exact status, JSON body, Allow {GET, POST, HEAD, OPTIONS},
Content-Language, no cookie, the Bearer challenge only on 401, Cache-Control:
no-store on every answer and no attachment. The adapter checks the exact runner
requests, the password attempt cache and the audit entry.
"""
import json
from pathlib import Path

from TESTS.contracts import http_family as family
from TESTS.contracts.http_family import require  # noqa: F401  (runner interface)
from TESTS.contracts.test_email_logs_http import SERVER_ERROR_DOCUMENT, ResponseFailure, difference, substitute
from TESTS.contracts.test_instance_backups_actions_http import language, send

SOURCE = Path(__file__).resolve().parents[1] / 'fixtures/instance_runtime_http.json'
ALLOWED = {'GET', 'POST', 'HEAD', 'OPTIONS'}

__all__ = ('require', 'load_source', 'assert_case', 'ResponseFailure')


def load_source(path=SOURCE):
    return family.load_source(path)


def assert_case(case, base_url, *, token, sessions):
    headers = {'Accept-Language': 'en', 'Accept': 'application/json', 'X-Correlation-ID': case['name']}
    if token:
        headers['Authorization'] = f'Bearer {token}'
    body = None
    if 'raw_body' in case:
        body = case['raw_body'].encode()
        headers['Content-Type'] = case['content_type']
    elif 'body' in case:
        body = json.dumps(case['body']).encode()
        headers['Content-Type'] = 'application/json'
    headers.update(substitute(case['headers'], sessions))
    status, raw, received = send(base_url, case['method'], case['path'], body, headers)

    def check(condition, code):
        if not condition:
            raise ResponseFailure(code, status)

    check(type(status) is int and status == case['status'], 'response.status')
    if case['response'] == '<stable-server-error-page>':
        check(raw == SERVER_ERROR_DOCUMENT, 'response.error-document')
        return status
    check(set(received.get('Allow', '').replace(' ', '').split(',')) == ALLOWED, 'response.allow')
    check(received.get('Content-Language') == language(headers) and received.get('Set-Cookie') is None, 'response.headers')
    check(received.get('WWW-Authenticate') == ('Bearer realm="api"' if status == 401 else None), 'response.authentication')
    check(received.get('Cache-Control') == 'no-store', 'response.cache-control')
    check(received.get('Content-Disposition') is None, 'response.no-attachment')
    check(received.get('Content-Type', '').split(';')[0] == 'application/json', 'response.type')
    try:
        actual = json.loads(raw)
    except (ValueError, UnicodeDecodeError):
        raise ResponseFailure('response.json', status) from None
    expected = case['response']
    check(type(actual) is type(expected) and actual == expected, 'response.body' + difference(expected, actual))
    return status
