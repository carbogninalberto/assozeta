"""Author the balance-sheet and balance-sheet/accounts/<uid>/delete HTTP sequence (balance-sheet.md).

balance_sheet (GET, POST, DELETE): IsAssociationUser, then role != ASSOCIATION
and a missing user.sportassociation are 403 {'msg': 'Info not available.'}.
GET (and POST with a non-null 'format') parses ?currentDate with
strptime('%Y-%m-%d') (default today), takes the balance year from the user's
start day/month (1 January here), and lists six available years ending with
today's balance year. It reads the association's newest sheet of that year
(archived included): an approved one is returned as stored; otherwise the
stored data (or the default data) is regenerated by generate_balance_sheet:
paid, amount > 0, live, non-archived payments of the association through the
group-aware Payment manager whose payment_date (or creation_date when null)
falls in [start 00:00, end 23:59:59], resetting their categories to 0 and
adding float(amount), appending missing categories and moving
meta_payment_categories amounts (categories resolved by id, unknown ones
skipped). Any exception inside the generation is swallowed and keeps the
partial data. Then bank/cash/other are the float sums of the per-account
Decimal balances up to the end date at 00:00 (initial balance, transfers in
the range, paid live payments with payment_date in the range), and total.
The sheet is created (audited) or saved (audited when something changed).
POST without 'format' replaces the newest sheet of any year with
data['balance_sheet'] (draft truthiness -> status, year as given; auditlog
records before Model.save converts the year). DELETE resets the year's sheet
to the default data. balance_sheet_accounts_delete gets the association's
account (otherwise 404 {'exception': ...}), refuses non-editable accounts, and
deletes the account with its transfers (each audited). Run with
``python3 -I``.
"""
