def moment(text):
    return text.replace('Z', '').replace('T', ' ')


def balance(label, end, group=None):
    """CustomAccountSerializer.get_current_balance_from(1970-01-01, end 00:00) as a float."""
    row = ACCOUNTS[label]
    limit = f'{end} 00:00:00'
    total = Decimal(row['initial'])
    for t in TRANSFERS.values():
        if moment(t['date']) <= limit:
            total += Decimal(t['amount']) if t['to'] == label else 0
            total -= Decimal(t['amount']) if t['from'] == label else 0
    for p in PAYMENTS.values():
        if (p['account'] == label and p['paid'] and not p['deleted'] and p['date'] is not None and moment(p['date']) <= limit
                and (group is None or p['group'] == group)):
            total += -Decimal(p['amount']) if p['expense'] else Decimal(p['amount'])
    return float(total)


def totals(data, end, group=None, association=OWN):
    """The view's bank/cash/other float sums and total, written into data."""
    for key, kind in (('bank', 2), ('cash', 1), ('other', 3)):
        data[key] = 0
        for label, row in ACCOUNTS.items():
            if row['association'] == association and row['type'] == kind:
                data[key] += balance(label, end, group)
    data['total'] = data['bank'] + data['cash'] + data['other']
    return data


