def save(label, data, actor, *, status=None, year=None):
    """Model.save() of a sheet: the stored state and auditlog's changed fields."""
    state = STATE[label]
    changes = {}
    if dumps(state['data']) != dumps(data):
        changes['data'] = [dumps(state['data']), dumps(data)]
    if status is not None and status != state['status']:
        changes['status_flag'] = [str(state['status']), str(status)]
        state['status'] = status
    if year is not None and str(year) != str(state['year']):
        changes['year'] = [str(state['year']), str(year)]
    state['data'] = json.loads(json.dumps(data))
    return {'kind': 'update', 'sheet': label, 'actor': actor, 'row': dict(state), 'changes': changes}


